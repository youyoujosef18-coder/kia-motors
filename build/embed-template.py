#!/usr/bin/env python3
"""
Embed the raw <x-dc> template so the page repairs itself without a network fetch.

Why: the DC runtime boots from the DOM, but a browser's HTML parser foster-parents
<sc-for> out of <tbody>, so every table-backed list (Inventory, Sales desk) loses its
rows. The runtime fixes this by re-fetching its own source and re-parsing the raw text
-- which fails on file:// URLs, where fetch is blocked. This embeds that raw text as a
base64 payload and hands it to the runtime directly, so the file works opened from disk.

Re-run after any edit to the template. Idempotent.
"""
import base64, io, re, sys

PATH = sys.argv[1] if len(sys.argv) > 1 else 'dealership-os.html'
MARK_OPEN  = '<!-- dc-raw-template: begin (generated by build/embed-template.py) -->'
MARK_CLOSE = '<!-- dc-raw-template: end -->'

src = io.open(PATH, encoding='utf-8').read()

# Drop any previous block so this can be re-run.
src = re.sub(re.escape(MARK_OPEN) + '.*?' + re.escape(MARK_CLOSE) + '\n?', '', src, flags=re.S)

# Exactly the slice the runtime's own parseDcText() takes.
open_tag = re.search(r'<x-dc(?:\s[^>]*)?>', src)
close_at = src.rfind('</x-dc>')
if not open_tag or close_at < 0:
    sys.exit('no <x-dc> block found in ' + PATH)
template = src[open_tag.end():close_at]

payload = base64.b64encode(template.encode('utf-8')).decode('ascii')

block = MARK_OPEN + '\n' + \
  '<script type="text/plain" id="dc-raw-template">' + payload + '</script>\n' + \
  '''<script>
/* Opened from disk, the runtime cannot fetch its own source to recover the raw
   template, so table rows built with <sc-for> never render. Hand it the template. */
(function () {
  if (location.protocol !== 'file:') return;
  var el = document.getElementById('dc-raw-template');
  if (!el) return;
  var bin = atob(el.textContent.trim());
  var bytes = new Uint8Array(bin.length);
  for (var i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
  var template = new TextDecoder('utf-8').decode(bytes);
  var tries = 0;
  var timer = setInterval(function () {
    if (++tries > 200) { clearInterval(timer); return; }
    if (typeof window.__dcUpdate !== 'function' || !window.__dcRegistry) return;
    var names = Object.keys(window.__dcRegistry);
    if (!names.length) return;
    clearInterval(timer);
    try { window.__dcUpdate(names[0], 'html', template, false); } catch (e) { /* no-op */ }
  }, 50);
})();
</script>\n''' + MARK_CLOSE + '\n'

src = src.replace('</body>', block + '</body>', 1)
io.open(PATH, 'w', encoding='utf-8').write(src)
print('embedded %d chars of template (%d chars base64) into %s' % (len(template), len(payload), PATH))
